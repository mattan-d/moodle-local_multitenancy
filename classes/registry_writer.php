namespace local_multitenancy;

defined('MOODLE_INTERNAL') || die();

/**
 * Writes registry.php consumed by bootstrap.php before Moodle starts.
 *
 * @package    local_multitenancy
 * @copyright  2026
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class registry_writer {

    /**
     * Resolve and ensure the registry directory ({dataroot}/multitenancy by default).
     *
     * @return string Absolute path or empty on failure.
     */
    public static function ensure_registry_dir(): string {
        global $CFG;

        $dir = '';
        if (function_exists('local_multitenancy_resolve_registry_dir')) {
            $dir = local_multitenancy_resolve_registry_dir($CFG);
        } else if (!empty($CFG->dataroot)) {
            $dir = rtrim((string) $CFG->dataroot, "/\\\0") . '/multitenancy';
        }
        if ($dir === '') {
            return '';
        }

        if (!is_dir($dir) && !make_writable_directory($dir, false)) {
            return '';
        }

        return $dir;
    }

    /**
     * Rebuild registry.php from the database.
     *
     * @return bool True if a file was written
     */
    public static function sync(): bool {
        global $DB;

        $dir = self::ensure_registry_dir();
        if ($dir === '') {
            return false;
        }

        $records = $DB->get_records('local_multitenancy_tenant', null, 'sortorder ASC, id ASC');
        $map = [];
        foreach ($records as $r) {
            $host = $r->host;
            if (function_exists('mb_strtolower')) {
                $host = mb_strtolower($host, 'UTF-8');
            } else {
                $host = strtolower($host);
            }
            $dboptions = [];
            if (!empty($r->dboptions)) {
                $decoded = json_decode($r->dboptions, true);
                if (is_array($decoded)) {
                    $dboptions = $decoded;
                }
            }
            $wwwroot = \local_multitenancy_normalize_public_wwwroot((string) $r->wwwroot);
            $map[$host] = [
                'id' => (int) $r->id,
                'shortcode' => $r->shortcode,
                'name' => $r->name,
                'enabled' => (int) $r->enabled,
                'provisionstatus' => (string) ($r->provisionstatus ?? tenant_provisioner::STATUS_COMPLETE),
                'midurim' => (string) ($r->midurim ?? ''),
                'midurimformat' => (int) ($r->midurimformat ?? FORMAT_HTML),
                'wwwroot' => $wwwroot,
                'dataroot' => $r->dataroot,
                'dbhost' => $r->dbhost,
                'dbname' => $r->dbname,
                'dbuser' => $r->dbuser,
                'dbpass' => (string) $r->dbpass,
                'prefix' => $r->dbprefix,
                'dbtype' => $r->dbtype,
                'dblibrary' => $r->dblibrary,
                'dboptions' => $dboptions,
            ];
        }

        $header = "<?php\n// This file is auto-generated by local_multitenancy. Do not edit manually.\n\n";
        $body = 'return ' . var_export($map, true) . ";\n";
        $target = $dir . '/registry.php';

        if (file_put_contents($target, $header . $body) === false) {
            return false;
        }
        @chmod($target, 0660);

        return true;
    }
}
